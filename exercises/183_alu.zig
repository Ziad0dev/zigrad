/// Make a freshly computed value fit its dtype.
fn fit(dtype: DType, x: f64) f64 {
    return switch (dtype) {
        .i32 => fromInt(wrapI32(toInt(x))),
        .f32 => ???,
        .bool => fromBool(x != 0),
        else => x, // weak types and void: as is
    };
